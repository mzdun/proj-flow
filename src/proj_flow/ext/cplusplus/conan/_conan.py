"""
The **proj_flow.ext.cplusplus.conan._conan** adds support for Conan v2 and,
deprecated, Conan v1.

.. deprecated:: 0.35

    Conan v1 has reached its end of support at JFrog. Its driver,
    :class:`conan_1`, is still used, when Conan v1 is found on ``PATH``, but
    it will be removed in a future version. Conan v2 is used in all other
    cases.
"""

import shutil
import subprocess
from abc import ABC, abstractmethod
from typing import Callable, List, cast

from typing_extensions import deprecated

from proj_flow.api.env import Config, Runtime
from proj_flow.base import cmd
from proj_flow.dependency import VER_REGEX


class conan(ABC):
    """
    Conan driver, base of :class:`conan_2` and the deprecated
    :class:`conan_1`.

    :param version: major version of Conan
    """

    version: int

    def __init__(self, version: int = 2):
        self.version = version

    def settings(self, cfg: Config):
        """
        Get the Conan settings from the config. Conan v2 uses
        ``conan2_settings``, falling back to ``conan_settings``, if missing;
        the deprecated Conan v1 uses only ``conan_settings``.

        :param cfg: config of current run
        :returns: list of the settings, empty, if none are configured
        """
        result: List[str] = []
        for threshold, name in enumerate(
            ["conan_settings", "conan2_settings"],
        ):
            if self.version <= threshold:
                break
            result = cast(List[str], cfg.items.get(name, result))
        return result

    @abstractmethod
    def config(
        self,
        rt: Runtime,
        conan_output_dir: str,
        compiler_profile_name: str,
        build_type_profile_name: str,
    ) -> int:
        """
        Detect the compiler profile and install the dependencies from the
        current directory, building missing packages.

        :param rt: runtime used for running Conan
        :param conan_output_dir: directory for the files generated by Conan
        :param compiler_profile_name: name of the profile to create with
            detected compiler
        :param build_type_profile_name: name of the profile used for both
            build and host contexts
        :returns: exit code, ``0`` on success
        """
        ...


@deprecated(
    "Conan v1 has reached its end of support; use Conan v2 and conan_2"
)
class conan_1(conan):
    """conan_1()

    Conan v1 driver.

    .. deprecated:: 0.35

        Conan v1 has reached its end of support; this driver will be removed
        in a future version. Use Conan v2 and :class:`conan_2`.
    """

    def __init__(self):
        super().__init__(1)

    def config(
        self,
        rt: Runtime,
        conan_output_dir: str,
        compiler_profile_name: str,
        build_type_profile_name: str,
    ) -> int:
        """
        Run ``conan profile new --detect`` and ``conan install`` with both
        ``-if`` and ``-of`` set to the output directory.

        :param rt: runtime used for running Conan
        :param conan_output_dir: directory for the files generated by Conan
        :param compiler_profile_name: name of the profile to create with
            detected compiler
        :param build_type_profile_name: name of the profile used for both
            build and host contexts
        :returns: exit code, ``0`` on success
        """
        if rt.cmd(
            "conan",
            "profile",
            "new",
            "--detect",
            "--force",
            compiler_profile_name,
        ):
            return 1

        return rt.cmd(
            "conan",
            "install",
            "-if",
            conan_output_dir,
            "-of",
            conan_output_dir,
            "--build",
            "missing",
            "-pr:b",
            build_type_profile_name,
            "-pr:h",
            build_type_profile_name,
            ".",
        )


class conan_2(conan):
    """Conan v2 driver."""

    def __init__(self):
        super().__init__(2)

    def config(
        self,
        rt: Runtime,
        conan_output_dir: str,
        compiler_profile_name: str,
        build_type_profile_name: str,
    ) -> int:
        """
        Run ``conan profile detect`` and ``conan install`` with ``-of`` set
        to the output directory.

        :param rt: runtime used for running Conan
        :param conan_output_dir: directory for the files generated by Conan
        :param compiler_profile_name: name of the profile to create with
            detected compiler
        :param build_type_profile_name: name of the profile used for both
            build and host contexts
        :returns: exit code, ``0`` on success
        """
        if rt.cmd(
            "conan",
            "profile",
            "detect",
            "--force",
            "--name",
            compiler_profile_name,
        ):
            return 1

        return rt.cmd(
            "conan",
            "install",
            "-of",
            conan_output_dir,
            "--build",
            "missing",
            "-pr:b",
            build_type_profile_name,
            "-pr:h",
            build_type_profile_name,
            ".",
        )


#: Major version assumed, when the version of Conan cannot be read.
DEFAULT_VERSION = 2


def _conan_version():
    found = shutil.which("conan")
    if found is None:
        return DEFAULT_VERSION

    proc = cast(
        subprocess.CompletedProcess[str],
        cmd.run(found, "--version", capture_output=True),
    )
    if proc is None or proc.returncode != 0:
        return DEFAULT_VERSION
    m = VER_REGEX.search(proc.stdout)
    version = m.group(0) if m is not None else None
    if version is None:
        return DEFAULT_VERSION
    chunks = [int(v.strip()) for v in version.split(".")]
    if len(chunks) < 1:
        return DEFAULT_VERSION
    return chunks[0]


ctors: List[Callable[[], conan]] = [
    conan_1,
    conan_2,
]


def conan_api() -> conan:
    """
    Create the driver for the Conan version found on ``PATH``. If Conan
    cannot be found, or its version cannot be read, Conan v2 is assumed;
    versions newer than v2 use the v2 driver, too. Only Conan v1 found on
    ``PATH`` selects the deprecated :class:`conan_1` driver.

    :returns: Conan driver
    """
    version = _conan_version()
    index = version - 1
    if index >= len(ctors):
        return ctors[-1]()
    return ctors[index]()
